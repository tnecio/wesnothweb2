#!/usr/bin/env node
/**
 * Phase 20: writes `apps/web/i18n/wesnothweb/wesnothweb.pot`, the template for
 * the port's own textdomain -- every msgid the UI and session hand to `tx()`
 * (or name `wesnothweb` explicitly). These are the strings Wesnoth upstream has
 * no counterpart for, so no translation exists; a translator adds
 * `apps/web/i18n/wesnothweb/<lang>.po` next to the template and
 * `build-translations.mjs` picks it up like any upstream domain.
 *
 * Extraction is the audit test's own (`packages/ui/src/i18n/extract.ts`), so
 * the two cannot disagree about what a call looks like. Run after adding or
 * changing a `tx('...')` string:
 *
 *   node --import tsx apps/web/scripts/extract-wesnothweb-pot.mjs
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';
import { extractMsgids } from '../../../packages/ui/src/i18n/extract.ts';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const outFile = path.join(repoRoot, 'apps/web/i18n/wesnothweb/wesnothweb.pot');

const MACHINERY = ['packages/ui/src/i18n/locale.ts', 'packages/ui/src/i18n/extract.ts'];

function walk(dir, exts, out = []) {
  for (const name of fs.readdirSync(dir)) {
    if (name === 'node_modules' || name.startsWith('.')) continue;
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) walk(full, exts, out);
    else if (exts.some((e) => name.endsWith(e)) && !/\.test\.ts$/.test(name)) out.push(full);
  }
  return out;
}

const files = [
  ...walk(path.join(repoRoot, 'packages/ui/src'), ['.svelte', '.ts']),
  ...walk(path.join(repoRoot, 'apps/web/src'), ['.svelte', '.ts']),
  ...walk(path.join(repoRoot, 'packages/engine/src'), ['.ts']),
].filter((f) => !MACHINERY.includes(path.relative(repoRoot, f)));

/** msgid -> { plural, refs } */
const entries = new Map();
for (const file of files) {
  const { uses } = extractMsgids(fs.readFileSync(file, 'utf8'));
  for (const u of uses) {
    if (u.domain !== 'wesnothweb') continue;
    const e = entries.get(u.msgid) ?? { plural: u.plural, refs: [] };
    e.refs.push(`${path.relative(repoRoot, file)}:${u.line}`);
    entries.set(u.msgid, e);
  }
}

const q = (s) =>
  s.length === 0
    ? '""'
    : s.includes('\n')
      ? '""\n' + s.split(/(?<=\n)/).map((l) => `"${l.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n')}"`).join('\n')
      : `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

let out = `# Port-only strings for wesnothweb2 (Wesnoth upstream has no counterpart for these).
# Generated by apps/web/scripts/extract-wesnothweb-pot.mjs -- do not edit by hand.
msgid ""
msgstr ""
"Project-Id-Version: wesnothweb2\\n"
"Content-Type: text/plain; charset=UTF-8\\n"
"Content-Transfer-Encoding: 8bit\\n"

`;
for (const msgid of [...entries.keys()].sort()) {
  const e = entries.get(msgid);
  out += `#: ${e.refs.slice(0, 3).join(' ')}\n`;
  out += `msgid ${q(msgid)}\n`;
  if (e.plural !== undefined) out += `msgid_plural ${q(e.plural)}\nmsgstr[0] ""\nmsgstr[1] ""\n\n`;
  else out += `msgstr ""\n\n`;
}
fs.writeFileSync(outFile, out);
console.log(`wrote ${entries.size} msgids to ${path.relative(repoRoot, outFile)}`);
