/** `red_to_green(val, for_text)`: `val` is a 0-100 percentage, clamped; nearest palette entry. */
export function redToGreen(val: number, forText = false): number {
  const scale = forText ? RED_GREEN_SCALE_TEXT : RED_GREEN_SCALE;
  const scaled = Math.min(1, Math.max(0, 0.01 * val));
  return scale[Math.round((scale.length - 1) * scaled)]!;
}
