#!/usr/bin/env node
/**
 * Regenerates `src/ai/config/builtinAiConfigs.generated.ts` from the real
 * upstream WML sources: `wesnoth/data/ai/utils/default_config.cfg` (the
 * `[default_config]` aspect defaults every side's `[ai]` config is built
 * on top of -- see `configuration::parse_side_config`) and each
 * `wesnoth/data/ai/ais/*.cfg` (the named `ai_algorithm=` presets:
 * `ai_default_rca`, `ai_default_rca_1_14`, `ai_experimental`, `idle_ai`).
 *
 * Why generated rather than read at runtime: these files are real WML,
 * `#define`-macro-based (`{AI_CA_GOTO}` etc., from `data/core/macros/
 * ai_candidate_actions.cfg`), and the browser has no WML preprocessor --
 * only `packages/engine`'s own node-only `wml/` parser does, and only
 * this script (run by hand, like `apps/web/scripts/build-scenario-
 * snapshot.mjs`) has access to `node:fs`. The generated module is
 * checked in so `packages/engine/src/ai/` can read it at runtime (node
 * AND browser) with zero preprocessing.
 *
 * Run from the repo root: `npx tsx packages/engine/scripts/gen-ai-configs.mjs`
 * Re-run whenever the `wesnoth` submodule is rebased and these files
 * changed upstream; `test/ai/builtinConfigsInSync.test.ts` regenerates
 * into a temp buffer and diffs against the checked-in module to catch
 * drift.
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseWmlFile, preloadDefinesFromDir } from '../src/wml/index.ts';

const engineRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = path.resolve(engineRoot, '../..');
const dataRoot = path.join(repoRoot, 'wesnoth/data');

const defines = new Map();
preloadDefinesFromDir(path.join(dataRoot, 'core'), defines, { dataRoot });
preloadDefinesFromDir(path.join(dataRoot, 'ai'), defines, { dataRoot });

/** Parses `ai/utils/default_config.cfg`: a bare sequence of top-level `[aspect]` tags (no `[ai]` wrapper -- see `data/_main.cfg`'s `[default_config]{ai/utils/default_config.cfg}[/default_config]`). */
function parseDefaultConfig() {
  const cfg = parseWmlFile(path.join(dataRoot, 'ai/utils/default_config.cfg'), { dataRoot, defines });
  const aspects = cfg.allChildren().filter((c) => c.tag === 'aspect');
  if (aspects.length === 0) {
    throw new Error('gen-ai-configs: default_config.cfg produced no [aspect] children -- upstream layout changed?');
  }
  return { attrs: {}, children: aspects.map((c) => ({ tag: c.tag, config: c.config.toJSON() })) };
}

/** Parses one `ai/ais/<id>.cfg`: expected to produce exactly one top-level `[ai]` child. */
function parseAiAlgorithmConfig(relPath) {
  const cfg = parseWmlFile(path.join(dataRoot, relPath), { dataRoot, defines });
  const aiChildren = cfg.allChildren().filter((c) => c.tag === 'ai');
  if (aiChildren.length !== 1) {
    throw new Error(`gen-ai-configs: ${relPath} produced ${aiChildren.length} top-level [ai] children, expected exactly 1`);
  }
  return aiChildren[0].config.toJSON();
}

const defaultConfig = parseDefaultConfig();
const algorithmFiles = {
  ai_default_rca: 'ai/ais/ai_default_rca.cfg',
  ai_default_rca_1_14: 'ai/ais/ai_default_rca_1_14.cfg',
  ai_experimental: 'ai/ais/ai_experimental.cfg',
  idle_ai: 'ai/ais/idle_ai.cfg',
};
const algorithmConfigs = {};
for (const [id, relPath] of Object.entries(algorithmFiles)) {
  algorithmConfigs[id] = parseAiAlgorithmConfig(relPath);
}

const header = `/**
 * GENERATED by packages/engine/scripts/gen-ai-configs.mjs -- do not hand-edit.
 * Source: \`wesnoth/data/ai/utils/default_config.cfg\` and \`wesnoth/data/ai/ais/*.cfg\`
 * (upstream 1.19.21+dev). See that script's own doc comment for why this is
 * checked in rather than parsed at runtime, and \`test/ai/
 * builtinConfigsInSync.test.ts\` for the drift check.
 */
import type { WmlConfigJson } from '../../wml/config.js';

/** The \`[default_config]\` aspect defaults (see \`configuration::parse_side_config\`): a bare list of \`[aspect]\` children with no enclosing \`[ai]\`. */
export const DEFAULT_AI_CONFIG_JSON: WmlConfigJson = ${JSON.stringify(defaultConfig, null, 2)};

/** The 4 named \`ai_algorithm=\` presets (\`data/ai/ais/*.cfg\`), each a single \`[ai]\` config. */
export const AI_ALGORITHM_CONFIGS_JSON: Record<string, WmlConfigJson> = ${JSON.stringify(algorithmConfigs, null, 2)};
`;

const outPath = path.join(engineRoot, 'src/ai/config/builtinAiConfigs.generated.ts');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, header);
console.log(`Wrote ${outPath} (${defaultConfig.children.length} default aspects, ${Object.keys(algorithmConfigs).length} algorithm configs).`);
